def _render_tfvars(env: str, run_id: str, lld_json: dict) -> str:
    template_str = _ENV_TEMPLATES.get(env, "")
    if not template_str:
        return f"# No template for env {env}\n"

    jinja = JinjaEnv(undefined=StrictUndefined)
    jinja.globals.update(b=_b, s=_s, list_s=_list_of_str)

    ctx = {
        "run_id": run_id,
        "meta": lld_json.get("_metadata", {}),
        "d1": lld_json.get("D1", {}),
        "d2": lld_json.get("D2", {}),
        "d3": lld_json.get("D3", {}),
        "d4": lld_json.get("D4", {}),
        "d5": lld_json.get("D5", {}),
        "d6": lld_json.get("D6", {}),
        "d7": lld_json.get("D7", {}),
        "d8": lld_json.get("D8", {}),
        "d9": lld_json.get("D9", {}),
    }
    return jinja.from_string(template_str).render(**ctx)


async def execute(state: "RunState", ctx: "StepContext") -> None:
    prefix = f"agent-runs/{state.run_id}/artifacts"
    state.artifacts_obs_prefix = prefix
    log.info("step08_artifacts_start", envs=state.deploy_envs)

    for env in state.deploy_envs:
        tfvars = _render_tfvars(env, state.run_id, state.lld_json)
        key = save_artifact(state.run_id, f"{env}/terraform.tfvars", tfvars)
        log.info("tfvars_generated", env=env, obs_key=key)

    # Also save the validated LLD as YAML for the approval email attachment reference
    import yaml as _yaml
    lld_out = {k: v for k, v in state.lld_json.items() if k in state.deploy_domains or k == "_metadata"}
    lld_yaml = _yaml.dump(lld_out, allow_unicode=True)
    save_artifact(state.run_id, "lld-validated.yaml", lld_yaml)
    log.info("lld_yaml_saved")
