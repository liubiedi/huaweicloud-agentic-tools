def _b(val: Any) -> str:
    """Render a boolean/string value as Terraform HCL literal."""
    if val is True or str(val).lower() in ("true", "yes"):
        return "true"
    if val is False or str(val).lower() in ("false", "no"):
        return "false"
    return str(val)


def _s(val: Any) -> str:
    """Render a string value quoted for HCL."""
    if val is None:
        return '""'
    return f'"{val}"'


def _list_of_str(val: Any) -> str:
    """Render a comma-separated string or list as HCL list literal."""
    if val is None:
        return "[]"
    if isinstance(val, list):
        items = val
    else:
        items = [v.strip() for v in str(val).split(",") if v.strip()]
    return "[" + ", ".join(f'"{i}"' for i in items) + "]"


